#!/usr/bin/env python3
"""Generate the root native build harness from the imported package manifests."""

import argparse
import json
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
PLATFORM_CRATES = {
    "gpui-apple-gpui-unofficial": 'cfg(any(target_os = "macos", target_os = "ios"))',
    "gpui-macos-gpui-unofficial": 'cfg(target_os = "macos")',
    "gpui-linux-gpui-unofficial": 'cfg(any(target_os = "linux", target_os = "freebsd"))',
    "gpui-windows-gpui-unofficial": 'cfg(target_os = "windows")',
    "gpui-web-gpui-unofficial": 'cfg(target_family = "wasm")',
}


def manifests(root):
    packages = {}
    for manifest in sorted((root / "gpui/crates").glob("*/Cargo.toml")):
        data = tomllib.loads(manifest.read_text())
        if "package" in data:
            name = data["package"]["name"]
            if name in packages:
                raise ValueError(f"Duplicate captured package: {name}")
            packages[name] = manifest.parent.relative_to(root).as_posix()
    if not packages:
        raise ValueError("No captured packages found")

    members = ["tools/build-all"]
    for manifest in sorted((root / "apps").glob("*/Cargo.toml")):
        members.append(manifest.parent.relative_to(root).as_posix())
    header = "# Generated by python3 scripts/update_build.py; do not edit.\n"
    workspace = [
        header.rstrip(),
        "[workspace]",
        'resolver = "2"',
        "members = " + json.dumps(members),
        "# Exact exclusions keep the captured standalone workspaces intact.",
        "exclude = [",
        *(f"    {json.dumps(path)}," for path in packages.values()),
        "]",
        "",
        "# Match the source release's property-test dependency.",
    ]
    pin = tomllib.loads((root / ".cargo/validation.toml").read_text())["patch"]["crates-io"]
    workspace.append("[patch.crates-io]")
    for name, options in sorted(pin.items()):
        fields = ", ".join(f"{key} = {json.dumps(value)}" for key, value in options.items())
        workspace.append(f"{name} = {{ {fields} }}")

    harness = [
        header.rstrip(),
        "[package]",
        'name = "xgpui-build"',
        'version = "0.0.0"',
        'edition = "2024"',
        "publish = false",
        "",
        "[features]",
        "runtime-shaders = [",
        '    "gpui-platform-gpui-unofficial/runtime_shaders",',
        '    "gpui-apple-gpui-unofficial/runtime_shaders",',
        '    "gpui-macos-gpui-unofficial/runtime_shaders",',
        "]",
        "",
        "[dependencies]",
    ]

    def dependency(name, features=()):
        fields = [f'path = "../../{packages[name]}"']
        if features:
            fields.append("features = " + json.dumps(list(features)))
        return f"{name} = {{ {', '.join(fields)} }}"

    for name in packages:
        if name not in PLATFORM_CRATES:
            harness.append(dependency(name))
    for name, condition in PLATFORM_CRATES.items():
        if name not in packages:
            continue
        harness.extend(["", f"[target.'{condition}'.dependencies]", dependency(name)])
        if name == "gpui-macos-gpui-unofficial":
            harness.append(dependency("gpui-platform-gpui-unofficial", ["font-kit"]))
        elif name == "gpui-linux-gpui-unofficial":
            harness.append(dependency("gpui-platform-gpui-unofficial", ["wayland", "x11"]))

    return {
        "Cargo.toml": "\n".join(workspace) + "\n",
        "tools/build-all/Cargo.toml": "\n".join(harness) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated manifests are stale")
    args = parser.parse_args()
    stale = []
    for name, content in manifests(ROOT).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, f"Stale build manifests: {', '.join(stale)}. Run python3 scripts/update_build.py\n")


if __name__ == "__main__":
    main()
