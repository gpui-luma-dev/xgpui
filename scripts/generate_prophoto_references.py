"""Generate independent ProPhoto RGB (ROMM RGB) oracles with 120-digit Decimals.

Native D50 colorants are solved from primary/white xy coordinates and adapted to
D65 with an independent Bradford implementation, rather than copied from Rust
constants. Transfer values use the exact piecewise definition: linear slope 16
below linear 1/512 (encoded 16/512) and the exact rational exponent 9/5.
No production implementation is imported.
References: https://www.w3.org/TR/css-color-4/#predefined-prophoto-rgb
            https://www.color.org/chardata/rgb/ROMMRGB.pdf (ISO 22028-2)
Run with --check to verify the committed fixture without changing it.
"""
import argparse
from decimal import Decimal as D, localcontext
import math
import struct
import subprocess
from pathlib import Path

from generate_adobe_rgb_references import PRIMARIES, array, inverse, matrix, multiply, number

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "extensions/crates/xgpui-color/tests/reference/prophoto_rgb.rs"
# CSS Color 4 publishes six-decimal primaries; ROMM's four-decimal values round
# to the same coefficients at the precision ROMM prints.
PROPHOTO = [("0.734699", "0.265301"), ("0.159597", "0.840403"), ("0.036598", "0.000105")]
D50 = ("0.3457", "0.3585")
D65 = ("0.3127", "0.3290")
# CSS Color 4 lin_ProPhoto_to_XYZ, checked here as provenance for the Rust literal.
CSS_TO_XYZ_D50 = [
    ["0.79776664490064230", "0.13518129740053308", "0.03134773412839220"],
    ["0.28807482881940130", "0.71183523424187300", "0.00008993693872564"],
    ["0", "0", "0.82510460251046020"],
]


def white(xy):
    x, y = D(xy[0]), D(xy[1])
    return [x / y, D(1), (D(1) - x - y) / y]


def solve(primaries, reference):
    xyz = [(D(x) / D(y), D(1), (D(1) - D(x) - D(y)) / D(y)) for x, y in primaries]
    columns = [[xyz[j][i] for j in range(3)] for i in range(3)]
    scales = [sum(v * w for v, w in zip(row, white(reference))) for row in inverse(columns)]
    return [[columns[i][j] * scales[j] for j in range(3)] for i in range(3)]


def bradford(source, destination):
    cone = [[D(v) for v in row] for row in [
        [".8951", ".2664", "-.1614"], ["-.7502", "1.7135", ".0367"], [".0389", "-.0685", "1.0296"]]]
    a = [sum(c * w for c, w in zip(row, white(source))) for row in cone]
    b = [sum(c * w for c, w in zip(row, white(destination))) for row in cone]
    return multiply(inverse(cone), [[cone[i][j] * b[i] / a[i] for j in range(3)] for i in range(3)])


def decode(x):
    x = D.from_float(x)
    return x / 16 if x <= D(16) / 512 else x ** (D(9) / 5)


def encode(x):
    x = D.from_float(x)
    return 16 * x if x < D(1) / 512 else x ** (D(5) / 9)


def generate():
    with localcontext() as ctx:
        ctx.prec = 120
        native = solve(PROPHOTO, D50)
        for row, css in zip(native, CSS_TO_XYZ_D50):
            for v, c in zip(row, css):
                assert abs(v - D(c)) < D("1e-16"), "CSS ProPhoto matrix provenance changed"
        to_xyz = multiply(bradford(D50, D65), native)
        from_xyz = inverse(to_xyz)
        others = [matrix(p) for p in PRIMARIES]  # sRGB, Display P3, Rec.2020, Adobe RGB
        identity = [[D(i == j) for j in range(3)] for i in range(3)]
        to_spaces = [multiply(inverse(m), to_xyz) for m in others] + [identity]
        from_spaces = [multiply(from_xyz, m) for m in others] + [identity]
        lines = [
            "// Generated by scripts/generate_prophoto_references.py; do not edit.",
            "// 120-digit Decimal oracle: D50 xy solve, independent Bradford to D65,",
            "// exact piecewise transfer. Space order: sRGB, Display P3, Rec.2020,",
            "// Adobe RGB (1998), ProPhoto RGB.",
        ]
        for name, value, kind in [
            ("TO_XYZ", to_xyz, "[[f64; 3]; 3]"),
            ("FROM_XYZ", from_xyz, "[[f64; 3]; 3]"),
            ("TO_SPACES", to_spaces, "[[[f64; 3]; 3]; 5]"),
            ("FROM_SPACES", from_spaces, "[[[f64; 3]; 3]; 5]"),
        ]:
            lines.append(f"pub const {name}: {kind} = {array(value)};")
        base = [i / 255 for i in range(256)]
        knees = []
        for k in [1 / 512, 16 / 512, 0.001953]:
            knees += [k, math.nextafter(k, 0.), math.nextafter(k, 1.)]
        edges = [math.ulp(0.), float.fromhex("0x1.0p-1022"),
                 math.nextafter(1., 0.), math.nextafter(1., math.inf), 1.25, 2.]
        logs = [10. ** e for e in [-300, -200, -100, -20, -12, -8, -4, 20, 100, 170]]
        for name, values, function in [
            ("DECODE_F64", sorted(set(base + knees + edges + logs)), decode),
            ("ENCODE_F64", sorted(set(base + knees + edges + logs + [1e200, 1e300,
                                  float.fromhex("0x1.fffffffffffffp+1023")])), encode),
        ]:
            pairs = [f"({number(x)}, {number(function(x))})" for x in values]
            lines.append(f"pub const {name}: &[(f64, f64)] = &[" + ", ".join(pairs) + "];")
        # Exact f32 inputs, so GPU comparisons do not count input rounding
        # against the shader. Includes both knees and their f32 neighbours.
        f32 = lambda x: struct.unpack("f", struct.pack("f", x))[0]
        up = lambda x: struct.unpack("<f", struct.pack("<I", struct.unpack("<I", struct.pack("<f", x))[0] + 1))[0]
        down = lambda x: struct.unpack("<f", struct.pack("<I", struct.unpack("<I", struct.pack("<f", x))[0] - 1))[0]
        gpu_knees = []
        for k in [1 / 512, 16 / 512]:
            gpu_knees += [k, up(k), down(k)]
        gpu = sorted(set(f32(x) for x in base + gpu_knees + [1e-12, 1e-8, 1e-4, 1.25, 2.]
                         + [1. - 2. ** -24, 1. + 2. ** -23]))
        bits = lambda x: struct.unpack("<I", struct.pack("<f", x))[0]
        triples = [f"(f32::from_bits(0x{bits(x):08x}), {number(decode(x))}, {number(encode(x))})" for x in gpu]
        lines.append("pub const TRANSFER_F32: &[(f32, f64, f64)] = &[" + ", ".join(triples) + "];")
        text = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"],
                              input="\n".join(lines) + "\n", text=True,
                              capture_output=True, check=True).stdout
        return {OUTPUT: text}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"ProPhoto RGB oracle fixture is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check:
        print("ProPhoto RGB oracle fixtures reproduced exactly.")


if __name__ == "__main__":
    main()
