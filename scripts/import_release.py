#!/usr/bin/env python3
"""Capture an immutable release snapshot without rewriting its source files."""

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import tarfile
import tempfile
import tomllib

SOURCE = "https://github.com/gpui-archipelago/gpui-unofficial.git"


def git(*args, cwd=None):
    return subprocess.check_output(["git", *args], cwd=cwd, text=True).strip()


def capture(root, source, revision, release, expected_sha=None):
    if not re.fullmatch(r"\d+\.\d+\.\d+", release):
        raise ValueError("Release must look like 1.25.2")
    sha = git("rev-parse", "--verify", f"{revision}^{{commit}}", cwd=source)
    if expected_sha and expected_sha.lower() != sha:
        raise ValueError(f"Expected {expected_sha}, found {sha}")

    with tempfile.TemporaryDirectory() as temporary:
        temporary = pathlib.Path(temporary)
        archive = temporary / "release.tar"
        subprocess.run(
            ["git", "archive", "--format=tar", f"--output={archive}", sha],
            cwd=source, check=True,
        )
        snapshot = temporary / "snapshot"
        snapshot.mkdir()
        with tarfile.open(archive) as contents:
            contents.extractall(snapshot, filter="data")

        packages = {}
        for manifest in sorted(snapshot.glob("crates/*/Cargo.toml")):
            data = tomllib.loads(manifest.read_text())
            package = data.get("package")
            if package is None:
                continue
            name = package["name"]
            if name in packages:
                raise ValueError(f"Duplicate package: {name}")
            if package["version"] != release:
                raise ValueError(f"{name} has unexpected version {package['version']}")
            packages[name] = "gpui/" + manifest.parent.relative_to(snapshot).as_posix()

        if "gpui-unofficial" not in packages:
            raise ValueError("Missing crates/gpui-unofficial/Cargo.toml")

        # Only replace the import directory, never the development branch tree.
        destination = root / "gpui"
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(snapshot, destination, symlinks=True)

        config = root / ".cargo" / "config.toml"
        config.parent.mkdir(exist_ok=True)
        lines = ["# Generated by scripts/import_release.py; do not edit.", "[patch.crates-io]"]
        for name, path in sorted(packages.items()):
            lines.append(f"{json.dumps(name)} = {{ path = {json.dumps(path)} }}")
        config.write_text("\n".join(lines) + "\n")

        provenance = {
            "repository": SOURCE.removesuffix(".git"),
            "ref": f"release/{release}",
            "commit": sha,
            "destination": "gpui",
            "packages": dict(sorted(packages.items())),
        }
        metadata = snapshot / "crates/transform-metadata.json"
        if metadata.exists():
            transformed = json.loads(metadata.read_text())
            provenance["zed_commit"] = transformed.get("zed_commit")
            provenance["zed_tag"] = transformed.get("zed_tag")
        (root / "upstream.json").write_text(json.dumps(provenance, indent=2) + "\n")
        return provenance


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release")
    parser.add_argument("--expected-sha")
    parser.add_argument("--source", type=pathlib.Path, help="Existing source checkout (offline testing)")
    args = parser.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+", args.release):
        parser.error("Release must look like 1.25.2")
    if args.expected_sha and not re.fullmatch(r"[0-9a-fA-F]{40}", args.expected_sha):
        parser.error("expected-sha must be a full 40-character SHA")

    root = pathlib.Path(git("rev-parse", "--show-toplevel"))
    if git("branch", "--show-current", cwd=root) != "upstream":
        parser.error("Imports must run on the upstream branch")
    if git("status", "--porcelain", cwd=root):
        parser.error("The checkout must be clean before importing")

    with tempfile.TemporaryDirectory() as temporary:
        if args.source:
            source = args.source.resolve()
            revision = "HEAD"
        else:
            source = pathlib.Path(temporary)
            subprocess.run(["git", "init", str(source)], check=True)
            subprocess.run(
                ["git", "fetch", "--depth=1", SOURCE, f"refs/heads/release/{args.release}"],
                cwd=source, check=True,
            )
            revision = "FETCH_HEAD"
        provenance = capture(root, source, revision, args.release, args.expected_sha)
        print(json.dumps(provenance, indent=2))


if __name__ == "__main__":
    main()
