"""Generate independent Adobe RGB test oracles with 120-digit Decimal arithmetic.

Matrices are solved from primary/white xy coordinates, not copied from Rust/WGSL
matrix constants. Transfer values use exact rational exponents and the exact
binary input value. No production implementation is imported.
Reference: https://www.w3.org/TR/css-color-4/#predefined-a98-rgb
Run with --check to verify the committed fixture without changing it.
"""
import argparse
from decimal import Decimal as D, localcontext
import math
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "extensions/crates/xgpui-color/tests/reference/adobe_rgb.rs"
FP16_OUTPUT = ROOT / "extensions/crates/xgpui-media/src/pipeline/adobe_fp16_reference.rs"
PRIMARIES = [
    [("0.64", "0.33"), ("0.30", "0.60"), ("0.15", "0.06")],
    [("0.68", "0.32"), ("0.265", "0.69"), ("0.15", "0.06")],
    [("0.708", "0.292"), ("0.170", "0.797"), ("0.131", "0.046")],
    [("0.64", "0.33"), ("0.21", "0.71"), ("0.15", "0.06")],
]


def inverse(matrix):
    # Independent pivoted Gauss-Jordan solution rather than the production
    # cofactor inverse or rational matrix literals.
    rows = [list(row) + [D(i == j) for j in range(3)] for i, row in enumerate(matrix)]
    for col in range(3):
        pivot = max(range(col, 3), key=lambda i: abs(rows[i][col]))
        rows[col], rows[pivot] = rows[pivot], rows[col]
        scale = rows[col][col]
        rows[col] = [v / scale for v in rows[col]]
        for i in range(3):
            if i != col:
                scale = rows[i][col]
                rows[i] = [v - scale * p for v, p in zip(rows[i], rows[col])]
    return [row[3:] for row in rows]


def multiply(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def matrix(primaries):
    xyz = [(D(x) / D(y), D(1), (D(1) - D(x) - D(y)) / D(y)) for x, y in primaries]
    columns = [[xyz[j][i] for j in range(3)] for i in range(3)]
    white = [D("0.3127") / D("0.3290"), D(1), (D(1) - D("0.3127") - D("0.3290")) / D("0.3290")]
    inv = inverse(columns)
    scales = [sum(v * w for v, w in zip(row, white)) for row in inv]
    return [[columns[i][j] * scales[j] for j in range(3)] for i in range(3)]


def number(value):
    value = float(value)
    if not math.isfinite(value):
        raise ValueError("Nonfinite oracle")
    return repr(value)


def array(value):
    if isinstance(value, list):
        return "[" + ", ".join(array(v) for v in value) + "]"
    return number(value)


def generate():
    with localcontext() as ctx:
        ctx.prec = 120
        matrices = [matrix(p) for p in PRIMARIES]
        adobe = matrices[3]
        inv_adobe = inverse(adobe)
        identity = [[D(i == j) for j in range(3)] for i in range(3)]
        lines = [
            "// Generated by scripts/generate_adobe_rgb_references.py; do not edit.",
            "// 120-digit Decimal oracle; primary/white xy solve + exact rational gamma.",
            "// Space order: sRGB, Display P3, Rec.2020, Adobe RGB (1998).",
        ]
        for name, value, kind in [
            ("TO_XYZ", adobe, "[[f64; 3]; 3]"),
            ("FROM_XYZ", inv_adobe, "[[f64; 3]; 3]"),
            ("TO_SPACES", [multiply(inverse(m), adobe) if i != 3 else identity for i, m in enumerate(matrices)], "[[[f64; 3]; 3]; 4]"),
            ("FROM_SPACES", [multiply(inv_adobe, m) if i != 3 else identity for i, m in enumerate(matrices)], "[[[f64; 3]; 3]; 4]"),
        ]:
            lines.append(f"pub const {name}: {kind} = {array(value)};")
        base = [i / 255 for i in range(256)]
        edges = [math.ulp(0.), float.fromhex("0x1.0p-1022"),
                 math.nextafter(1., 0.), math.nextafter(1., math.inf), 1.25, 2.]
        logs = [10. ** e for e in [-300, -200, -150, -148, -147, -146, -145, -144, -143, -142, -141, -140, -139, -100, -20, -12, -8, -4, 20, 100, 140]]
        for name, values, exponent in [
            ("DECODE_F64", sorted(set(base + edges + logs)), D(563) / 256),
            ("ENCODE_F64", sorted(set(base + edges + logs + [1e200, 1e300, float.fromhex("0x1.fffffffffffffp+1023")])), D(256) / 563),
        ]:
            pairs = [f"({number(x)}, {number(D.from_float(x) ** exponent)})" for x in values]
            lines.append(f"pub const {name}: &[(f64, f64)] = &[" + ", ".join(pairs) + "];")
        # Exact f32 inputs, so the GPU comparison does not count input rounding
        # against the shader. All nonzero outputs here are normal f32 values.
        f32 = lambda x: struct.unpack("f", struct.pack("f", x))[0]
        gpu = sorted(set(f32(x) for x in base + [1e-17, 1e-16, 1e-12, 1e-8, 1e-4, 1.25, 2.]
                         + [1. - 2. ** -24, 1. + 2. ** -23]))
        triples = [f"(f32::from_bits(0x{struct.unpack('<I', struct.pack('<f', x))[0]:08x}), {number(D.from_float(x) ** (D(563)/256))}, {number(D.from_float(x) ** (D(256)/563))})" for x in gpu]
        lines.append("pub const TRANSFER_F32: &[(f32, f64, f64)] = &[" + ", ".join(triples) + "];")
        def formatted(text):
            return subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"],
                                  input=text, text=True, capture_output=True, check=True).stdout

        half_rows = []
        for encoded in [0.0001, 0.0005, 0.001, 0.003, 0.18, 0.5]:
            linear = D.from_float(f32(encoded)) ** (D(563) / 256)
            for alpha in [1., 0.5]:
                bits = struct.unpack("<H", struct.pack("<e", float(linear * D.from_float(alpha))))[0]
                half_rows.append(f"({number(encoded)}, {number(alpha)}, 0x{bits:04x})")
        half = [
            "// Generated by scripts/generate_adobe_rgb_references.py; do not edit.",
            "// Exact f32 input -> Decimal(120-digit) gamma -> associated binary16.",
            "// All spaces use D65, so neutral gray is unchanged by primaries.",
            "const ADOBE_FP16_GRAY_REFERENCES: &[(f32, f32, u16)] = &["
                + ", ".join(half_rows) + "];",
        ]
        rec_rows = []
        # Independent source conversion and FP16 quantization, including alpha,
        # corners outside P3, near-black storage, and odd-width mip averages.
        for source in [1, 3]:
            transform = multiply(inverse(matrices[2]), matrices[source])
            for rgb in [(r, g, b) for r in [0., .001, .18, .5, 1.]
                        for g in [0., .001, .18, .5, 1.]
                        for b in [0., .001, .18, .5, 1.]]:
                values = [D.from_float(f32(v)) for v in rgb]
                if source == 3:
                    values = [v ** (D(563) / 256) for v in values]
                for alpha in [0., .25, .5, 1.]:
                    linear = [sum(x * y for x, y in zip(row, values)) for row in transform]
                    associated = [max(D(0), min(D(1), v)) * D.from_float(alpha) for v in linear]
                    bits = [struct.unpack("<H", struct.pack("<e", float(v)))[0] for v in associated]
                    rec_rows.append(f"({str(source == 3).lower()}, {array(list(rgb) + [alpha])}, [{', '.join(f'0x{x:04x}' for x in bits)}])")
        rec = formatted("// Generated by scripts/generate_adobe_rgb_references.py; do not edit.\n"
                        "// Independent 120-digit source xy matrices/gamma -> associated FP16.\n"
                        "const REC2020_REFERENCES: &[(bool, [f32; 4], [u16; 3])] = &["
                        + ", ".join(rec_rows) + "];\n")
        native_rows = []
        rec_to_p3 = multiply(inverse(matrices[1]), matrices[2])
        for r in [0., 2. ** -14, .5, 1.]:
            for g in [0., 2. ** -14, .5, 1.]:
                for b in [0., 2. ** -14, .5, 1.]:
                    for alpha in [0., .5, 1.]:
                        # Texture contains associated half values; oracle starts
                        # from those exact stored inputs, independently of CPU math.
                        bits = [struct.unpack("<H", struct.pack("<e", v * alpha))[0] for v in [r,g,b]]
                        values = [D.from_float(struct.unpack("<e", struct.pack("<H", v))[0]) for v in bits]
                        rgb = [sum(x*y for x,y in zip(row, values)) for row in rec_to_p3]
                        out = [struct.unpack("<H", struct.pack("<e", float(v)))[0] for v in rgb]
                        bits += [struct.unpack("<H", struct.pack("<e", alpha))[0]]
                        native_rows.append("([" + ",".join(f"0x{v:04x}" for v in bits) + "], [" + ",".join(f"0x{v:04x}" for v in out) + "])")
        native = formatted("// Generated independent 120-digit xy matrix solve; exact half inputs.\n"
                           "const REC2020_P3_REFERENCES: &[([u16;4],[u16;3])] = &[" + ",".join(native_rows) + "];\n")
        return {
            ROOT / "gpui/crates/gpui-apple/src/metal_renderer/wide_sdr/rec2020_reference.rs": native,
            ROOT / "extensions/crates/xgpui-media/src/pipeline/rec2020_reference.rs": rec,
            OUTPUT: formatted("\n".join(lines) + "\n"),
            FP16_OUTPUT: formatted("\n".join(half) + "\n"),
        }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"Adobe RGB oracle fixture is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check:
        print("Adobe RGB CPU/GPU and FP16 oracle fixtures reproduced exactly.")


if __name__ == "__main__":
    main()
