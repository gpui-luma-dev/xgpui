"""Independent 120-digit Bradford vectors. Run with --check to verify.

Uses a pivoted Gauss-Jordan inverse, exact decimal cone coefficients and exact
binary64 input values. No production color constants or implementation imported.
Conventions: https://www.w3.org/TR/css-color-4/#color-conversion-code
"""
from decimal import Decimal as D, localcontext
from pathlib import Path
import argparse
import struct
from generate_adobe_rgb_references import inverse, array, matrix as rgb_matrix, PRIMARIES

ROOT = Path(__file__).resolve().parents[1]
MEDIA_OUTPUT = ROOT / 'extensions/crates/xgpui-media/src/pipeline/d50_fp16_reference.rs'
OUTPUT = Path(__file__).resolve().parents[1] / 'extensions/crates/xgpui-color/tests/reference/bradford.rs'


def multiply(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(len(b)))
             for j in range(len(b[0]))] for i in range(len(a))]


def generate():
    with localcontext() as ctx:
        ctx.prec = 120
        cone = [[D(v) for v in row] for row in [
            ['.8951', '.2664', '-.1614'], ['-.7502', '1.7135', '.0367'], ['.0389', '-.0685', '1.0296']]]
        whites = []
        for x, y in [('.3457', '.3585'), ('.3127', '.3290')]:
            x, y = D(x), D(y)
            whites.append([[x/y], [D(1)], [(1-x-y)/y]])
        out = ['// Generated by scripts/generate_bradford_references.py; do not edit.',
               '// (source_is_d50, exact f64 input, 120-digit adapted XYZ rounded to f64)',
               '#[rustfmt::skip]',
               'pub const VECTORS: &[(bool, [f64; 3], [f64; 3])] = &[']
        for direction in range(2):
            src, dst = whites[direction], whites[1-direction]
            a, b = multiply(cone, src), multiply(cone, dst)
            matrix = multiply(inverse(cone), [[cone[i][j]*b[i][0]/a[i][0] for j in range(3)] for i in range(3)])
            inputs = [[x, y, z] for x in [-2., 0., .18, 1., 2.]
                      for y in [-.5, 0., .5, 1.] for z in [-1., 0., .001, 1., 3.]]
            inputs += [[v, -v, v] for v in [1e-300, 1e-100, 1e100, 1e300]]
            for values in inputs:
                exact = [[D.from_float(v)] for v in values]
                result = [row[0] for row in multiply(matrix, exact)]
                out.append(f'    ({str(direction == 0).lower()}, {array(values)}, {array(result)}),')
        out.append('];\n')
        # Independent D50 diagonal colorants → CAT → Rec.2020 → clip → associate.
        a, b = multiply(cone, whites[0]), multiply(cone, whites[1])
        cat = multiply(inverse(cone), [[cone[i][j]*b[i][0]/a[i][0] for j in range(3)] for i in range(3)])
        diagonal = [[whites[0][i][0] if i == j else D(0) for j in range(3)] for i in range(3)]
        conversion = multiply(inverse(rgb_matrix(PRIMARIES[2])), multiply(cat, diagonal))
        media = ['// Generated by scripts/generate_bradford_references.py; do not edit.',
                 '#[rustfmt::skip]', 'const D50_FP16: &[([f32; 4], [u16; 4])] = &[']
        for rgba in [[0.,1.,0.,.5], [1.,0.,0.,1.], [0.,0.,1.,.25], [.18,.18,.18,1.], [1.,1.,1.,0.]]:
            rgba = [struct.unpack('<f', struct.pack('<f', v))[0] for v in rgba]
            rgb = multiply(conversion, [[D.from_float(v)] for v in rgba[:3]])
            alpha = D.from_float(rgba[3])
            mapped = [min(D(1), max(D(0), row[0]))*alpha for row in rgb] + [alpha]
            bits = [struct.unpack('<H',struct.pack('<e',float(v)))[0] for v in mapped]
            media.append(f'    ({array(rgba)}, [{", ".join(f"0x{v:04x}" for v in bits)}]),')
        media.append('];\n')
        return {OUTPUT: '\n'.join(out), MEDIA_OUTPUT: '\n'.join(media)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for output, content in generate().items():
        if args.check:
            if output.read_text() != content:
                raise SystemExit(f'Bradford fixture differs: {output}')
        else:
            output.write_text(content)
    if args.check:
        print('Bradford and D50 FP16 oracles reproduced exactly.')
